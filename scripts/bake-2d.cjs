// Dev tool: bakes the 3D models into 2D editor assets (products-baked.js).
// Usage: npm run bake   (needs Playwright + Chromium, and Python3 with opencv-python-headless)
const { chromium } = require('playwright');
const { build } = require('esbuild');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

(async () => {
  const root = path.resolve(__dirname, '..');
  const tmp = fs.mkdtempSync(path.join(require('os').tmpdir(), 'bake-'));
  await build({ entryPoints: [path.join(__dirname, 'bake-page.js')], bundle: true, loader: { '.glb': 'binary' }, outfile: path.join(tmp, 'b.js'), logLevel: 'error' });
  fs.writeFileSync(path.join(tmp, 'i.html'), '<script src="b.js"></script>');
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage();
  page.on('pageerror', (e) => console.error(e));
  await page.goto('file://' + path.join(tmp, 'i.html'));
  const out = await page.evaluate(() => window.bake());
  await browser.close();
  // trace each silhouette into an SVG path (editor units) with OpenCV
  for (const id of Object.keys(out)) for (const vk of Object.keys(out[id])) {
    const v = out[id][vk];
    const png = path.join(tmp, `${id}-${vk}.png`);
    fs.writeFileSync(png, Buffer.from(v.mask.split(',')[1], 'base64'));
    v.shape = execFileSync('python3', [path.join(__dirname, 'trace.py'), png]).toString().trim();
    delete v.mask;
  }
  const js = '// Generated by scripts/bake-2d.cjs — real 3D models rendered for the 2D editor.\n' +
    "'use strict';\nconst BAKED = " + JSON.stringify(out) + ';\n';
  fs.writeFileSync(path.join(root, 'products-baked.js'), js);
  console.log('wrote products-baked.js', (js.length / 1024).toFixed(0) + 'KB');
})();
